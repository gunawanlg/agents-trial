"""Parse a production logistic scorecard written as a SQL SELECT.

The query shape this module understands is the one generated by typical
scorecard platforms (CASE WHEN WoE bins, ``LN(p/(1-p))`` logit / VAL
columns, then a linear combination folded through a sigmoid):

::

    select 1/(1+exp(-s.LINEAR_SCORE)) as SCORE, s.*
    from (
        select w.col_WOE * b1 + ... + w.Intercept * b0 as LINEAR_SCORE, w.*
        from (
            select
                case when raw < t then woe ... end as col_WOE,
                case when 1=1 then nvl(LN(p/(1-p)), impute) end as col_VAL,
                ...
            from source
        ) w
    ) s

:func:`parse_scorecard_sql` returns the column lists the rest of the package
needs (``cols_pred``, ``cols_pred_woe``, ``cols_pred_used``), a grouping
definition with the SQL null-imputation values, a scikit-learn
:class:`~sklearn.linear_model.LogisticRegression` whose ``coef_`` / ``intercept_``
reproduce ``LINEAR_SCORE = B^T X``, and a human-readable formula.
"""

import os
import re
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional, Sequence, Tuple

import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression

from scorecard_segment_eval.binning import (
    MISSING_LABEL,
    OTHER_LABEL,
    BinningModel,
    BinSpec,
    edge_labels,
)
from scorecard_segment_eval.schema import Gates, ScorecardColumns

_CASE_RE = re.compile(r"\bcase\s+(.*?)\s+end\s+as\s+([A-Za-z_][\w]*)", re.I | re.S)
_LINEAR_RE = re.compile(r"select\s+(.*?)\s+as\s+LINEAR_SCORE", re.I | re.S)
_TERM_RE = re.compile(
    r"(?:[A-Za-z_][\w]*\.)?([A-Za-z_][\w]*)\s*\*\s*([+-]?(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?)"
)
_FROM_RE = re.compile(r"\bfrom\s+([A-Za-z_][\w]*(?:\.[A-Za-z_][\w]*)?|_SOURCETABLENAME_)", re.I)
_NUMBER_RE = re.compile(r"^[+-]?(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?$")
_IDENT_RE = r"([A-Za-z_][\w]*)"
_LOGIT_NVL_RE = re.compile(
    r"(?:nvl|coalesce)\s*\(\s*ln\s*\(\s*%(id)s\s*/\s*\(\s*1\s*-\s*%(id)s\s*\)\s*\)\s*,\s*"
    r"([+-]?(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?)\s*\)" % {"id": _IDENT_RE},
    re.I,
)
_LOGIT_RE = re.compile(
    r"ln\s*\(\s*%(id)s\s*/\s*\(\s*1\s*-\s*%(id)s\s*\)\s*\)" % {"id": _IDENT_RE},
    re.I,
)
_EQ_RE = re.compile(r"^%s\s*=\s*(?:'([^']*)'|\"([^\"]*)\"|(\S+))\s*$" % _IDENT_RE, re.I)
_CMP_RE = re.compile(
    r"^%s\s*(<=|>=|<|>)\s*([+-]?(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?)\s*$" % _IDENT_RE,
    re.I,
)
_NULL_RE = re.compile(r"^%s\s+is\s+null\s*$" % _IDENT_RE, re.I)
_TRUE_RE = re.compile(r"^1\s*=\s*1$")
_WOE_SUFFIXES = ("_woe",)
_VAL_SUFFIXES = ("_val", "_lin")


def _strip_sql_comments(sql):
    # type: (str) -> str
    text = re.sub(r"/\*.*?\*/", " ", sql, flags=re.S)
    lines = []
    for line in text.splitlines():
        if "--" in line:
            line = line[: line.index("--")]
        lines.append(line)
    return "\n".join(lines)


def _looks_like_woe(name):
    # type: (str) -> bool
    return str(name).lower().endswith("_woe")


def _looks_like_val(name):
    # type: (str) -> bool
    lowered = str(name).lower()
    return any(lowered.endswith(suf) for suf in _VAL_SUFFIXES)


def _is_intercept(name):
    # type: (str) -> bool
    return str(name).lower() == "intercept"


def _parse_number(text):
    # type: (str) -> Optional[float]
    text = str(text).strip().rstrip(",")
    if not _NUMBER_RE.match(text):
        return None
    return float(text)


def _parse_then(expr):
    # type: (str) -> Dict[str, Any]
    text = str(expr).strip().rstrip(",")
    nvl = _LOGIT_NVL_RE.search(text)
    if nvl:
        return {"kind": "logit", "raw": nvl.group(1), "impute": float(nvl.group(3))}
    logit = _LOGIT_RE.search(text)
    if logit:
        return {"kind": "logit", "raw": logit.group(1), "impute": None}
    number = _parse_number(text)
    if number is not None:
        return {"kind": "number", "value": number}
    return {"kind": "unknown", "raw_sql": text}


def _split_whens(body):
    # type: (str) -> Tuple[List[Tuple[str, str]], Optional[str]]
    else_val = None  # type: Optional[str]
    else_m = re.search(r"\belse\s+(.*)$", body, re.I | re.S)
    core = body
    if else_m:
        else_val = else_m.group(1).strip()
        core = body[: else_m.start()]
    pairs = re.findall(r"when\s+(.*?)\s+then\s+(.*?)(?=\s+when\s+|\s*$)", core, re.I | re.S)
    cleaned = [(cond.strip(), then.strip()) for cond, then in pairs]
    return cleaned, else_val


def _parse_condition(cond):
    # type: (str) -> Dict[str, Any]
    text = cond.strip()
    if _TRUE_RE.match(text):
        return {"op": "true"}
    null_m = _NULL_RE.match(text)
    if null_m:
        return {"op": "null", "raw": null_m.group(1)}
    eq_m = _EQ_RE.match(text)
    if eq_m:
        value = eq_m.group(2)
        if value is None:
            value = eq_m.group(3)
        if value is None:
            value = eq_m.group(4)
        return {"op": "eq", "raw": eq_m.group(1), "value": value}
    cmp_m = _CMP_RE.match(text)
    if cmp_m:
        op_map = {"<": "lt", "<=": "le", ">": "gt", ">=": "ge"}
        return {
            "op": op_map[cmp_m.group(2)],
            "raw": cmp_m.group(1),
            "threshold": float(cmp_m.group(3)),
        }
    return {"op": "unknown", "raw_sql": text}


def _case_to_spec(alias, body):
    # type: (str, str) -> Tuple[Optional[BinSpec], Optional[str], List[str]]
    """Return ``(spec, raw_column, notes)``.  Intercept yields no spec."""
    notes = []  # type: List[str]
    pairs, else_sql = _split_whens(body)
    else_parsed = _parse_then(else_sql) if else_sql is not None else None
    parsed_whens = [(_parse_condition(c), _parse_then(t)) for c, t in pairs]

    if _is_intercept(alias):
        return None, None, notes

    logit_whens = [(c, t) for c, t in parsed_whens if t.get("kind") == "logit"]
    if logit_whens:
        _cond, then = logit_whens[0]
        raw = then["raw"]
        impute = then.get("impute")
        if impute is not None:
            notes.append("null_impute: %s" % (impute,))
        else:
            notes.append("no_null_imputation")
        spec = BinSpec(
            feature=str(raw),
            kind="logit",
            method="sql_logit",
            transform="logit",
            impute=impute,
            output_name=alias,
            notes=notes,
            labels=["logit"],
            woe={"logit": 0.0, MISSING_LABEL: float(impute) if impute is not None else 0.0},
        )
        return spec, str(raw), notes

    raw = None  # type: Optional[str]
    rules = []  # type: List[Dict[str, Any]]
    eq_groups = {}  # type: Dict[str, List[str]]
    eq_woe = {}  # type: Dict[str, float]
    lt_cuts = []  # type: List[Tuple[float, float]]
    ge_cuts = []  # type: List[Tuple[float, float]]
    null_woe = None  # type: Optional[float]
    else_woe = None  # type: Optional[float]
    if else_parsed and else_parsed.get("kind") == "number":
        else_woe = float(else_parsed["value"])

    for cond, then in parsed_whens:
        if then.get("kind") != "number":
            notes.append("unparsed_then: %s" % (then,))
            continue
        woe = float(then["value"])
        op = cond.get("op")
        if cond.get("raw"):
            raw = raw or str(cond["raw"])
        if op == "eq":
            value = str(cond.get("value"))
            label_key = None
            for existing, members in eq_groups.items():
                if eq_woe.get(existing) == woe:
                    label_key = existing
                    members.append(value)
                    break
            if label_key is None:
                label_key = value
                eq_groups[label_key] = [value]
                eq_woe[label_key] = woe
            rules.append({"op": "eq", "value": value, "woe": woe, "label": label_key})
        elif op in ("lt", "le", "gt", "ge"):
            threshold = float(cond["threshold"])
            if op in ("lt", "le"):
                lt_cuts.append((threshold, woe))
            else:
                ge_cuts.append((threshold, woe))
            rules.append(
                {
                    "op": op,
                    "threshold": threshold,
                    "woe": woe,
                    "label": None,
                }
            )
        elif op == "null":
            null_woe = woe
            rules.append({"op": "null", "woe": woe, "label": MISSING_LABEL})
            notes.append("null_impute: %s" % (woe,))
        else:
            notes.append("unparsed_when: %s" % (cond,))

    if else_woe is not None:
        rules.append({"op": "else", "woe": else_woe, "label": OTHER_LABEL})
        if null_woe is None:
            notes.append("else_impute: %s" % (else_woe,))

    if raw is None:
        return None, None, notes

    cuts = sorted(set([t for t, _w in lt_cuts] + [t for t, _w in ge_cuts]))
    has_numeric = bool(cuts)
    has_eq = bool(eq_groups)
    kind = "mixed" if (has_numeric and has_eq) else ("numeric" if has_numeric else "categorical")

    edges = None  # type: Optional[List[float]]
    labels = []  # type: List[str]
    groups = {}  # type: Dict[str, List[str]]
    woe_map = {}  # type: Dict[str, float]
    closed = "left" if has_numeric else "right"

    if has_numeric:
        edges = [float("-inf")] + [float(c) for c in cuts] + [float("inf")]
        labels = edge_labels(edges, closed="left")
        # Attach numeric labels to matching lt/ge rules in CASE order.
        numeric_rule_idx = [i for i, r in enumerate(rules) if r["op"] in ("lt", "le", "gt", "ge")]
        # Walk bins left to right; each bin maps to the first covering rule.
        for i, label in enumerate(labels):
            lo, hi = edges[i], edges[i + 1]
            probe = 0.5 * (lo + hi) if np.isfinite(lo) and np.isfinite(hi) else (lo + 1.0 if np.isfinite(lo) else hi - 1.0)
            if not np.isfinite(probe):
                probe = 0.0
            for ridx in numeric_rule_idx:
                rule = rules[ridx]
                thr = float(rule["threshold"])
                op = rule["op"]
                covers = False
                if op == "lt" and probe < thr:
                    covers = True
                elif op == "le" and probe <= thr:
                    covers = True
                elif op == "gt" and probe > thr:
                    covers = True
                elif op == "ge" and probe >= thr:
                    covers = True
                if covers and rule.get("label") is None:
                    rule["label"] = label
                    woe_map[label] = float(rule["woe"])
                    break
            else:
                woe_map.setdefault(label, else_woe if else_woe is not None else 0.0)

    for label, members in eq_groups.items():
        pretty = "|".join(sorted(set(members)))
        if len(pretty) > 60:
            pretty = label
        groups[pretty] = list(members)
        woe_map[pretty] = eq_woe[label]
        labels = labels + [pretty] if pretty not in labels else labels
        for rule in rules:
            if rule.get("op") == "eq" and rule.get("value") in members:
                rule["label"] = pretty

    if null_woe is not None:
        woe_map[MISSING_LABEL] = float(null_woe)
    elif else_woe is not None:
        woe_map[MISSING_LABEL] = float(else_woe)
        notes.append("null_falls_through_to_else: %s" % (else_woe,))
    if else_woe is not None:
        woe_map[OTHER_LABEL] = float(else_woe)

    impute_val = null_woe if null_woe is not None else else_woe
    spec = BinSpec(
        feature=str(raw),
        kind=kind,
        method="sql_case",
        edges=edges,
        groups=groups or None,
        labels=[lab for lab in labels if lab],
        woe=woe_map,
        closed=closed,
        impute=impute_val,
        output_name=alias,
        notes=notes,
        rules=rules,
    )
    return spec, str(raw), notes


def _parse_linear_terms(sql):
    # type: (str) -> List[Tuple[str, float]]
    match = _LINEAR_RE.search(sql)
    region = match.group(1) if match else sql
    terms = []  # type: List[Tuple[str, float]]
    for name, coef in _TERM_RE.findall(region):
        terms.append((str(name), float(coef)))
    return terms


def logistic_from_coefficients(feature_names, coefficients, intercept):
    # type: (Sequence[str], Sequence[float], float) -> LogisticRegression
    """A sklearn logistic regressor with ``coef_`` / ``intercept_`` set directly."""
    model = LogisticRegression(C=1e12, solver="lbfgs", max_iter=1)
    model.classes_ = np.array([0, 1])
    model.coef_ = np.asarray(list(coefficients), dtype=float).reshape(1, -1)
    model.intercept_ = np.array([float(intercept)], dtype=float)
    try:
        model.n_features_in_ = int(len(feature_names))
    except Exception:
        pass
    try:
        model.n_iter_ = np.array([0], dtype=np.int32)
    except Exception:
        pass
    return model


def _format_formula(terms, intercept):
    # type: (Sequence[Tuple[str, float]], float) -> str
    parts = []
    x_names = []
    for name, coef in terms:
        if _is_intercept(name):
            continue
        if parts:
            parts.append("  + %s * %.16g" % (name, float(coef)))
        else:
            parts.append("  %s * %.16g" % (name, float(coef)))
        x_names.append(name)
    parts.append("  + Intercept * %.16g" % (float(intercept),))
    x_names.append("1")
    b_names = [name for name, _c in terms if not _is_intercept(name)] + ["Intercept"]
    lines = [
        "PD = 1/(1+exp(-LINEAR_SCORE))",
        "LINEAR_SCORE = B^T X",
        "X = [%s]" % (", ".join(x_names),),
        "B = [%s]" % (", ".join(b_names),),
        "",
        "LINEAR_SCORE =",
        "\n".join(parts),
    ]
    return "\n".join(lines)


@dataclass
class ScorecardSQLModel:
    """Parsed production logistic scorecard."""

    cols_pred: List[str] = field(default_factory=list)
    cols_pred_woe: List[str] = field(default_factory=list)
    cols_pred_used: List[str] = field(default_factory=list)
    pred_map: Dict[str, str] = field(default_factory=dict)
    coefficients: Dict[str, float] = field(default_factory=dict)
    intercept: float = 0.0
    formula: str = ""
    grouping: Optional[BinningModel] = None
    model: Any = None
    source_table: Optional[str] = None
    score_alias: str = "SCORE"
    messages: List[str] = field(default_factory=list)

    def to_columns(self, col_id, **kwargs):
        # type: (str, Any) -> ScorecardColumns
        payload = dict(
            col_id=col_id,
            cols_pred=list(self.cols_pred),
            cols_pred_woe=list(self.cols_pred_woe),
            cols_pred_used=list(self.cols_pred_used),
            pred_map=dict(self.pred_map),
        )
        payload.update(kwargs)
        return ScorecardColumns(**payload)

    def to_artifact(self):
        # type: () -> FittedModelArtifact
        from scorecard_segment_eval.refit import FittedModelArtifact

        return FittedModelArtifact(
            kind="pooled",
            method="logistic_sql",
            grouping=self.grouping,
            model=self.model,
            feature_names=list(self.grouping.columns) if self.grouping is not None else list(self.cols_pred),
            pred_woe_map=dict((k, v) for k, v in self.pred_map.items() if _looks_like_woe(v)),
            coefficients=dict(self.coefficients),
            messages=list(self.messages),
        )

    def save_grouping(self, path):
        # type: (str) -> str
        if self.grouping is None:
            raise ValueError("ScorecardSQLModel has no grouping to save")
        return self.grouping.save(path)

    def predict_proba(self, frame):
        # type: (Any) -> np.ndarray
        """sklearn-style ``(n, 2)`` probabilities for classes 0 and 1."""
        pd_hat = np.asarray(self.to_artifact().predict_proba(frame), dtype=float).reshape(-1)
        return np.column_stack([1.0 - pd_hat, pd_hat])

    def transform_frame(self, frame, score_col="SCORE", linear_col="LINEAR_SCORE"):
        # type: (Any, str, str) -> Any
        """Return a copy of ``frame`` with transformed columns, linear score and PD."""
        base = pd.DataFrame(frame).reset_index(drop=True)
        mapped = self.grouping.transform_woe(frame) if self.grouping is not None else pd.DataFrame()
        out = base.copy()
        for col in mapped.columns:
            alias = self.pred_map.get(col, col)
            out[alias] = mapped[col].to_numpy()
        if self.model is not None and self.grouping is not None and len(self.grouping.columns):
            matrix = mapped[self.grouping.columns].to_numpy(dtype=float)
            linear = matrix.dot(self.model.coef_[0]) + float(self.model.intercept_[0])
            out[linear_col] = linear
            out[score_col] = 1.0 / (1.0 + np.exp(-np.clip(linear, -30.0, 30.0)))
        return out

    def to_dict(self):
        # type: () -> Dict[str, Any]
        return {
            "cols_pred": list(self.cols_pred),
            "cols_pred_woe": list(self.cols_pred_woe),
            "cols_pred_used": list(self.cols_pred_used),
            "pred_map": dict(self.pred_map),
            "coefficients": dict(self.coefficients),
            "intercept": float(self.intercept),
            "formula": self.formula,
            "source_table": self.source_table,
            "score_alias": self.score_alias,
            "messages": list(self.messages),
        }


def parse_scorecard_sql(sql):
    # type: (str) -> ScorecardSQLModel
    """Parse a scorecard SQL string into columns, grouping, formula and an LR."""
    cleaned = _strip_sql_comments(sql)
    messages = []  # type: List[str]
    cases = _CASE_RE.findall(cleaned)
    if not cases:
        raise ValueError("no CASE ... END AS alias expressions found in the scorecard SQL")

    specs = {}  # type: Dict[str, BinSpec]
    pred_map = {}  # type: Dict[str, str]
    cols_pred = []  # type: List[str]
    cols_pred_woe = []  # type: List[str]
    for body, alias in cases:
        spec, raw, case_notes = _case_to_spec(alias, body)
        messages.extend(case_notes)
        if _is_intercept(alias):
            continue
        if raw is None:
            messages.append("could_not_parse_case: %s" % (alias,))
            continue
        if raw not in cols_pred:
            cols_pred.append(raw)
        pred_map[raw] = alias
        if _looks_like_woe(alias) and alias not in cols_pred_woe:
            cols_pred_woe.append(alias)
        if spec is not None:
            specs[raw] = spec

    terms = _parse_linear_terms(cleaned)
    if not terms:
        raise ValueError("no LINEAR_SCORE terms (alias * coefficient) found in the scorecard SQL")

    intercept = 0.0
    used = []  # type: List[str]
    coefs = {}  # type: Dict[str, float]
    for name, coef in terms:
        if _is_intercept(name):
            intercept = float(coef)
            coefs["__intercept__"] = float(coef)
            continue
        used.append(name)
        coefs[name] = float(coef)

    # Feature order for the sklearn model: raw columns in LINEAR_SCORE order.
    raw_order = []  # type: List[str]
    inverse = dict((v, k) for k, v in pred_map.items())
    for name in used:
        raw = inverse.get(name, name)
        if raw not in raw_order:
            raw_order.append(raw)
    for raw in cols_pred:
        if raw not in raw_order:
            raw_order.append(raw)

    grouping = BinningModel(specs=specs, gates=Gates())
    grouping.columns = [c for c in raw_order if c in specs]
    beta = []
    for raw in grouping.columns:
        alias = pred_map.get(raw, raw)
        beta.append(float(coefs.get(alias, 0.0)))
    model = logistic_from_coefficients(grouping.columns, beta, intercept)

    from_m = _FROM_RE.findall(cleaned)
    source_table = from_m[-1] if from_m else None

    parsed = ScorecardSQLModel(
        cols_pred=cols_pred,
        cols_pred_woe=cols_pred_woe,
        cols_pred_used=used,
        pred_map=pred_map,
        coefficients=coefs,
        intercept=intercept,
        formula=_format_formula(terms, intercept),
        grouping=grouping,
        model=model,
        source_table=source_table,
        messages=messages,
    )
    return parsed


def parse_scorecard_sql_path(path):
    # type: (str) -> ScorecardSQLModel
    with open(path, "r") as handle:
        return parse_scorecard_sql(handle.read())
